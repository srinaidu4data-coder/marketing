/**
 * Link this machine to the ONE Admin database (Vercel Production Postgres).
 *
 * Usage:
 *   node scripts/use-admin-db.mjs
 *
 * Then paste DATABASE_URL and DIRECT_URL when prompted (or pass as env).
 * Writes yantra-portal/.env.local (gitignored).
 */
import { writeFileSync, readFileSync, existsSync } from "fs";
import { createInterface } from "readline";
import { spawnSync } from "child_process";

const envLocal = new URL("../.env.local", import.meta.url);
// fileURLToPath for windows
import { fileURLToPath } from "url";
const envLocalPath = fileURLToPath(envLocal);

function isPg(u) {
  return /^postgres(ql)?:\/\//i.test((u || "").trim());
}

function ask(q) {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) =>
    rl.question(q, (a) => {
      rl.close();
      resolve(a.trim());
    })
  );
}

let databaseUrl = (process.env.DATABASE_URL || "").trim();
let directUrl = (process.env.DIRECT_URL || "").trim();

if (!isPg(databaseUrl)) {
  console.log(`
════════════════════════════════════════════════════════════
 SINGLE ADMIN DATABASE
 Paste the SAME values as Vercel → roleforge → Production.
 Dashboard: https://vercel.com → roleforge → Settings → Env
════════════════════════════════════════════════════════════
`);
  // Non-interactive agents cannot paste secrets — fail with clear steps
  if (!process.stdin.isTTY) {
    console.error(`
Non-interactive mode: set env then re-run:

  set DATABASE_URL=postgresql://...from-vercel...
  set DIRECT_URL=postgresql://...from-vercel...
  node scripts/use-admin-db.mjs

Or create .env.local manually with those two lines.
`);
    process.exit(1);
  }
  databaseUrl = await ask("DATABASE_URL (postgresql://…): ");
  directUrl =
    (await ask("DIRECT_URL (or Enter to reuse DATABASE_URL): ")) || databaseUrl;
}

if (!isPg(databaseUrl)) {
  console.error("DATABASE_URL must start with postgresql://");
  process.exit(1);
}
if (!directUrl) directUrl = databaseUrl;

// Preserve other keys from existing .env.local / .env if present
function loadKeys(path) {
  const out = {};
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const i = line.indexOf("=");
    const k = line.slice(0, i).trim();
    let v = line.slice(i + 1).trim();
    out[k] = v;
  }
  return out;
}

const base = {
  ...loadKeys(fileURLToPath(new URL("../.env", import.meta.url))),
  ...loadKeys(envLocalPath),
};
base.DATABASE_URL = JSON.stringify(databaseUrl).slice(1, -1); // escape-ish
// Write properly quoted
const lines = [
  "# Generated by scripts/use-admin-db.mjs — SINGLE Admin Postgres",
  "# Same DATABASE_URL as Vercel Production. Do not use file:./dev.db.",
  `DATABASE_URL="${databaseUrl.replace(/"/g, '\\"')}"`,
  `DIRECT_URL="${directUrl.replace(/"/g, '\\"')}"`,
];
// Keep non-DB keys from previous .env.local
for (const [k, v] of Object.entries(loadKeys(envLocalPath))) {
  if (k === "DATABASE_URL" || k === "DIRECT_URL") continue;
  if (k.startsWith("//")) continue;
  lines.push(`${k}=${v}`);
}

writeFileSync(envLocalPath, lines.join("\n") + "\n", "utf8");
console.log("Wrote", envLocalPath);

// Generate postgres client
const gen = spawnSync(
  process.execPath,
  ["node_modules/prisma/build/index.js", "generate", "--schema=prisma/schema.prisma"],
  {
    cwd: fileURLToPath(new URL("..", import.meta.url)),
    env: { ...process.env, DATABASE_URL: databaseUrl, DIRECT_URL: directUrl },
    stdio: "inherit",
  }
);
if (gen.status !== 0) process.exit(gen.status || 1);

// Verify connection + list candidates
const check = spawnSync(
  process.execPath,
  ["--import", "tsx", "scripts/_list-candidates-from-env.mjs"],
  {
    cwd: fileURLToPath(new URL("..", import.meta.url)),
    env: { ...process.env, DATABASE_URL: databaseUrl, DIRECT_URL: directUrl },
    stdio: "inherit",
  }
);
process.exit(check.status || 0);
